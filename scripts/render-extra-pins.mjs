function fail(message) {
    console.error(`\nError: ${message}\n`);
    process.exit(1);
}

function assertCopy(spec) {
    const title = spec.title.trim();
    const headline = spec.headline.trim();
    const subline = spec.subline.trim();
    const body = spec.body.trim();
    const description = `${body} ${CLOSE}`;
    if (!BOARDS.has(spec.suggestedBoard)) fail(`${spec.asin} board is not in the list: ${spec.suggestedBoard}`);
    if (title.length > 100) fail(`${spec.asin} ${spec.file} title is ${title.length} chars`);
    if (!title.includes(': ')) fail(`${spec.asin} ${spec.file} title needs a colon hook`);
    const keyword = title.split(': ')[0];
    if (keyword.length < 8) fail(`${spec.asin} title keyword is too short`);
    if (description.length < 300 || description.length > 500) {
        fail(`${spec.asin} ${spec.file} description is ${description.length} chars`);
    }
    if (!description.endsWith(CLOSE)) fail(`${spec.asin} description closer missing`);
    for (const field of [headline, subline, spec.kicker]) {
        if (/\$|christmas|santa|price/i.test(field)) fail(`${spec.asin} image text has a blocked claim: ${field}`);
    }
    if (subline.length > 38) fail(`${spec.asin} ${spec.file} subline is ${subline.length} chars: ${subline}`);
    if (spec.kicker.length > 16) fail(`${spec.asin} kicker too long: ${spec.kicker}`);
    const lines = wrapText(headline, 18, 4);
    if (lines.join(' ') !== headline || lines.some((line) => line.length > 18)) {
        fail(`${spec.asin} ${spec.file} headline wraps badly:\n  ${lines.map((l) => `${l.length} ${l}`).join('\n  ')}`);
    }
    const base = path.basename(spec.scene).toLowerCase();
    if (base.startsWith('amazon') || base.startsWith('pinterest') || base.startsWith('source')) {
        fail(`${spec.asin} refuses scene ${spec.scene}`);
    }
    return { title, description, headline, subline, lines };
}

async function reviewSlugs() {
    const dir = 'src/content/reviews';
    const names = (await fs.readdir(dir)).filter((name) => name.endsWith('.md'));
    const map = new Map();
    for (const name of names) {
        const raw = await fs.readFile(path.join(dir, name), 'utf8');
        const asin = raw.match(/^asin:\s*"?([A-Za-z0-9]+)"?/m)?.[1]?.toUpperCase();
        if (!asin) fail(`No asin in ${name}`);
        map.set(asin, name.replace(/\.md$/, ''));
    }
    return map;
}

